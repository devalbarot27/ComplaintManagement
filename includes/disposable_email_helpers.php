function disposable_email_extract_domain(string $email): string
{
    $email = strtolower(trim($email));
    $atPos = strrpos($email, '@');
    if ($atPos === false) {
        return '';
    }

    return substr($email, $atPos + 1);
}

/**
 * True when the email uses a known disposable / open / anonymous provider.
 */
function disposable_email_is_blocked(string $email): bool
{
    $domain = disposable_email_extract_domain($email);
    if ($domain === '') {
        return false;
    }

    $blocked = disposable_email_blocked_domains();
    if (in_array($domain, $blocked, true)) {
        return true;
    }

    // Also block subdomains of blocked providers (e.g. foo.mailinator.com).
    foreach ($blocked as $blockedDomain) {
        $suffix = '.' . $blockedDomain;
        if (strlen($domain) > strlen($suffix) && substr($domain, -strlen($suffix)) === $suffix) {
            return true;
        }
    }

    return false;
}

function disposable_email_blocked_message(): string
{
    return 'Open or disposable email addresses are not allowed. Please use a valid personal or business email.';
}
